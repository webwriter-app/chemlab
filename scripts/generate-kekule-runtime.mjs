import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

// The official browser modules resolve their classes through window. Loading a
// second copy then replaces the classes used by molecules already in the lab.
// Keep the same modules, in their official order, in one lexical scope.
const require = createRequire(import.meta.url);
const dist = dirname(dirname(require.resolve("kekule/mod/io")));
const modules = ["root", "localization", "common", "data", "core", "algorithm", "io", "html", "render"];
const sources = await Promise.all(modules.map(name => readFile(join(dist, "mins", `${name}.min.js`), "utf8")));
const license = await readFile(join(dist, "..", "LICENSE"), "utf8");

function replaceOnce(source, before, after) {
	const index = source.indexOf(before);
	if (index < 0 || source.indexOf(before, index + before.length) >= 0) {
		throw new Error(`Kekulé bootstrap changed near ${before}. Check the runtime scope before updating it.`);
	}
	return source.slice(0, index) + after + source.slice(index + before.length);
}

let root = sources[0];
root = replaceOnce(root,
	'"object"==typeof self?e=self:"object"==typeof window&&window.document?e=window:"object"==typeof global&&(e=global);',
	"");
root = replaceOnce(root,
	'e.DataType=a,a.StringUtils=o}(this),function(e)',
	'e.DataType=a,a.StringUtils=o}(this);const {Class, ClassEx, ObjectEx, DataType} = this;!function(e)');
root = replaceOnce(root,
	'Kekule.$jsRoot=this,"object"==typeof window&&window&&window.document?Kekule.$jsRoot=window:"object"==typeof global?Kekule.$jsRoot=global:"object"==typeof self&&(Kekule.$jsRoot=self),',
	'Kekule.$jsRoot=this,');

const output = `/*! Kekulé.js modules. Generated by scripts/generate-kekule-runtime.mjs.
${license.trim().replaceAll("\r", "")}
*/

const scope = {
	document: globalThis.document,
	Node: globalThis.Node,
	setTimeout: globalThis.setTimeout.bind(globalThis),
};
export const Kekule = (function () {
${[root, ...sources.slice(1)].map(source => source.trim().replaceAll("\r", "")).join("\n")}
Kekule._loaded();
return Kekule;
}).call(scope);
`;

const target = new URL("../chemlib/vendor/kekule-runtime.mjs", import.meta.url);
if (process.argv.includes("--check")) {
	if (await readFile(target, "utf8") !== output) throw new Error("The Kekulé runtime needs to be regenerated.");
} else {
	await writeFile(target, output);
}

// Bundle this entry for a browser with esbuild, then open the bundle from an
// HTML page. Copy the text in <pre> to data/chemicalPreviews.generated.ts.
import { StructureManager } from "../chemlib";
import { chemicalCatalog } from "../data/chemicals";
import { loadMoleculeDefinition } from "../data/moleculeDefinition";

const previews = new Map<string, { image: string; index: number }>();
const names: [string, number][] = [];
const output = document.createElement("pre");
try {
	for (const { name, preview } of chemicalCatalog) {
		if (!preview) continue;
		const key = JSON.stringify(preview);
		if (!previews.has(key)) {
			const molecule = loadMoleculeDefinition(preview);
			if (molecule._bondCount !== preview.bonds.length || molecule._atomCount !== preview.atoms.length) {
				throw new Error(`Incomplete structure for ${name}`);
			}
			const image = StructureManager.printMolecule(molecule, 80, 60, 14);
			if (!image.startsWith("data:image/png;base64,")) throw new Error(`PNG generation failed for ${name}`);
			previews.set(key, { image, index: previews.size });
		}
		names.push([name, previews.get(key).index]);
	}
	output.textContent = [
		"// Generated by scripts/render-chemical-previews.ts.",
		"const structures = [",
		...Array.from(previews.values(), ({ image }) => `\t${JSON.stringify(image)},`),
		"];",
		"",
		"export const catalogPreviews: Partial<Record<string, string>> = {",
		...names.map(([name, index]) => `\t${JSON.stringify(name)}: structures[${index}],`),
		"};",
	].join("\n");
} catch (error) {
	output.textContent = String(error);
}
document.body.append(output);
